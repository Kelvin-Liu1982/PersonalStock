"""
构建中远海控(601919.SH / 01919.HK) 2026 年回购明细 Excel。
数据来源：公司回购公告 / 港交所翌日披露 / 证券时报·数据宝 / 公司官网新闻（交叉核对）。

说明：
  - 用户要求"今年来 A股和H股的历史明细"。本文件整理 2026 年以来（含 2025 披露、2026 完成的第4轮）
    以及 2026 年内逐日 H股回购明细。
  - A股回购按"轮次"汇总关键里程碑；H股回购给出 2026.03.23–2026.05.22 逐日明细（21 次）及累计。
  - H股第4轮（2025-10~12，1.233亿股）已在 2025 年完成注销，作为历史汇总单列。
  - 2026.05.22 之后的 H股逐日数据、以及第5轮 H股回购（2026股东会授权）如有后续公告，需补入后刷新。
单位：A股金额/价格为人民币(元/亿元)；H股金额/价格为港币(港元/万港元)。
"""
import os, openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "数据源", "中远海控_回购明细.xlsx")

HEAD_FILL = PatternFill("solid", fgColor="1F2733")
HEAD_FONT = Font(color="FFFFFF", bold=True, size=11)
thin = Side(style="thin", color="D5DCE4")
BORDER = Border(left=thin, right=thin, top=thin, bottom=thin)

def style_sheet(ws, headers, rows_data, widths, num_cols=()):
    ws.append(headers)
    for c in range(1, len(headers) + 1):
        cell = ws.cell(row=1, column=c)
        cell.fill = HEAD_FILL; cell.font = HEAD_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER
    for ri, row in enumerate(rows_data, start=2):
        for ci, val in enumerate(row, start=1):
            cell = ws.cell(row=ri, column=ci, value=val)
            cell.border = BORDER
            if ci == 1:
                cell.font = Font(bold=True)
                cell.alignment = Alignment(horizontal="center")
            else:
                cell.alignment = Alignment(horizontal="right")
            if ci in num_cols and isinstance(val, (int, float)):
                cell.number_format = "0.00"
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"

wb = openpyxl.Workbook()

