BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
CENTER = Alignment(horizontal="center", vertical="center", wrap_text=True)
LEFT = Alignment(horizontal="left", vertical="center", wrap_text=True)
RIGHT = Alignment(horizontal="right", vertical="center")

def style_header(ws, row, ncols):
    for c in range(1, ncols + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = HDR_FILL
        cell.font = HDR_FONT
        cell.alignment = CENTER
        cell.border = BORDER

def write_table(ws, start_row, headers, rows, note_col=None):
    """通用写表：headers 列表；rows 为元组列表 (第一列指标名, [各列值], 备注)。"""
    ncols = len(headers)
    for j, h in enumerate(headers, 1):
        ws.cell(row=start_row, column=j, value=h)
    style_header(ws, start_row, ncols)
    r = start_row + 1
    for item in rows:
        name = item[0]
        vals = item[1]
        note = item[2] if len(item) > 2 else ""
        c1 = ws.cell(row=r, column=1, value=name)
        c1.font = METRIC_BOLD
        c1.alignment = LEFT
        c1.border = BORDER
        for k, v in enumerate(vals, 2):
            cell = ws.cell(row=r, column=k, value=v)
            cell.font = METRIC_FONT
            cell.alignment = RIGHT if not isinstance(v, str) else CENTER
            cell.border = BORDER
            if isinstance(v, float):
                cell.number_format = "#,##0.00"
        if note or note_col is not None:
            nc = ws.cell(row=r, column=ncols, value=note)
            nc.font = SUB_FONT
            nc.alignment = LEFT
            nc.border = BORDER
            if note:
                nc.fill = NOTE_FILL
        r += 1
    return r

def autosize(ws, widths):
    for col, w in widths.items():
        ws.column_dimensions[col].width = w

def build_file(fname, title, annual_headers, annual_rows, q_headers, q_rows, source_text,
               annual_subtitle=None, annual_widths=None):
    wb = openpyxl.Workbook()
    # ---- Sheet1 年报数据 ----
    ws = wb.active
    ws.title = "年报数据"
    ws.cell(row=1, column=1, value=title).font = TITLE_FONT
    if annual_subtitle is None:
        annual_subtitle = "口径：全年累计（除特别标注）；单位见各行；2026 为计划/中报值，单列于备注。"
    ws.cell(row=2, column=1, value=annual_subtitle).font = SUB_FONT
    end = write_table(ws, 4, annual_headers, annual_rows)
    if annual_widths is None:
        annual_widths = {"A": 34, "B": 13, "C": 13, "D": 13, "E": 13, "F": 13, "G": 13, "H": 40}
    autosize(ws, annual_widths)
    ws.freeze_panes = "B5"
    # ---- Sheet2 季报数据 ----
    ws2 = wb.create_sheet("季报数据")
    ws2.cell(row=1, column=1, value=title + " · 季报数据").font = TITLE_FONT
    ws2.cell(row=2, column=1, value="口径：单季 Q1/Q2/Q3/Q4（非累计）。Q1=一季报；Q2=中报-一季报；Q3=三季报-中报；Q4=年报-三季报。").font = SUB_FONT
    write_table(ws2, 4, q_headers, q_rows)
    qwidths = {"A": 12}
    for i in range(2, len(q_headers) + 1):
        qwidths[openpyxl.utils.get_column_letter(i)] = 16
    qwidths[openpyxl.utils.get_column_letter(len(q_headers))] = 34
    autosize(ws2, qwidths)
    ws2.freeze_panes = "B5"
    # ---- Sheet3 数据来源与口径说明 ----
    ws3 = wb.create_sheet("数据来源与口径说明")
    ws3.cell(row=1, column=1, value=title + " · 数据来源与口径说明").font = TITLE_FONT
    r = 3
    for line in source_text:
        c = ws3.cell(row=r, column=1, value=line)
        c.font = METRIC_FONT if not line.startswith("·") else SUB_FONT
        c.alignment = LEFT
        ws3.merge_cells(start_row=r, start_column=1, end_row=r, end_column=6)
        r += 1
    ws3.column_dimensions["A"].width = 110
    wb.save(f"{OUT}/{fname}")
    print("已生成:", fname)

def pct(v):
    if v is None:
        return "—"
    return ("+" if v >= 0 else "") + ("%.1f%%" % v)

def yoy(cur, prev):
    if prev is None or prev == 0:
        return "—"
    return pct((cur / prev - 1) * 100)

